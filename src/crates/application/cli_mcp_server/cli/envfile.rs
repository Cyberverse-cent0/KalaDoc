//! `.env` file generation for required secrets.
//!
//! [`AppConfig`](crate::config::AppConfig) requires three env-only
//! secrets (`APP_SECRET_KEY`, `APP_DB_USER`, `APP_DB_PASSWORD`). Rather
//! than making every first-run user hand-craft them, `kaladoc init`
//! calls [`ensure_env_file`] to materialize a `.env` in the working
//! directory containing cryptographically random values for whichever
//! keys are not already provided by the process environment or an
//! existing `.env`.
//!
//! Guarantees:
//!
//! - **Never overwrites** — keys already present (in the environment or
//!   in the file) are preserved byte-for-byte; only missing keys are
//!   appended.
//! - **Never leaks into the wrong place** — the file is created with
//!   mode `0600` on Unix, matching the credentials-file policy.
//! - **dotenvy-compatible** — plain `KEY=value` lines; `dotenv()`
//!   picks them up on the next [`AppConfig::load`], and existing
//!   process-env values still win (dotenvy never overrides).

use std::io;
use std::path::{Path, PathBuf};

use rand_core::{OsRng, RngCore};
use serde::Serialize;

/// The secret keys [`ensure_env_file`] knows how to generate.
const SECRET_KEYS: &[&str] = &["APP_SECRET_KEY", "APP_DB_USER", "APP_DB_PASSWORD"];

/// Which `.env` keys were generated on this run.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum EnvKeyStatus {
    /// A fresh random value was generated and written.
    Generated,
    /// Already set in the process environment — not written to the
    /// file (dotenvy would ignore it anyway).
    FromEnvironment,
    /// Already present in the existing `.env` — preserved.
    AlreadyInFile,
}

/// Per-key outcome of [`ensure_env_file`]. Values are never included —
/// this type is safe to serialize into command output.
#[derive(Debug, Clone, Serialize)]
pub struct EnvFileReport {
    /// Path of the `.env` file (or the one that would have been used).
    pub path: PathBuf,
    /// `true` when the file was created or appended to this run.
    pub modified: bool,
    /// Key → what happened to it.
    pub keys: Vec<EnvKeyEntry>,
}

/// One row of [`EnvFileReport::keys`].
#[derive(Debug, Clone, Serialize)]
pub struct EnvKeyEntry {
    pub key: &'static str,
    pub status: EnvKeyStatus,
}

/// Ensures `.env` (or `path`) contains every required secret key,
/// generating random values for the ones that are missing.
///
/// Resolution order per key: process environment → existing file →
/// freshly generated. Returns a report describing what changed; the
/// file is only written when at least one key needed generating.
pub fn ensure_env_file(path: &Path) -> io::Result<EnvFileReport> {
    let existing = match std::fs::read_to_string(path) {
        Ok(contents) => contents,
        Err(e) if e.kind() == io::ErrorKind::NotFound => String::new(),
        Err(e) => return Err(e),
    };
    let file_keys = parse_keys(&existing);

    let mut entries = Vec::with_capacity(SECRET_KEYS.len());
    let mut additions: Vec<(&'static str, String)> = Vec::new();

    for &key in SECRET_KEYS {
        if std::env::var_os(key).is_some_and(|v| !v.is_empty()) {
            entries.push(EnvKeyEntry {
                key,
                status: EnvKeyStatus::FromEnvironment,
            });
        } else if file_keys.iter().any(|(k, _)| *k == key) {
            entries.push(EnvKeyEntry {
                key,
                status: EnvKeyStatus::AlreadyInFile,
            });
        } else {
            entries.push(EnvKeyEntry {
                key,
                status: EnvKeyStatus::Generated,
            });
            additions.push((key, generate_secret(key)));
        }
    }

    let modified = !additions.is_empty();
    if modified {
        let mut block = String::new();
        if !existing.is_empty() {
            block.push('\n'); // blank line separating generated block
        }
        block.push_str("# Generated by `kaladoc init` — keep this file secret.\n");
        for (key, value) in &additions {
            block.push_str(&format!("{key}={value}\n"));
        }
        write_private(path, block.as_bytes())?;
    }

    Ok(EnvFileReport {
        path: path.to_path_buf(),
        modified,
        keys: entries,
    })
}

/// Default `.env` location: the current working directory, matching
/// where `dotenvy::dotenv()` searches.
pub fn default_env_path() -> PathBuf {
    PathBuf::from(".env")
}

/// Parses `KEY=value` / `KEY = value` / `export KEY=value` lines into
/// `(KEY, value)` pairs. Comments and blanks are ignored; a key counts
/// as present even with an empty value (the user explicitly set it).
fn parse_keys(contents: &str) -> Vec<(&str, &str)> {
    contents
        .lines()
        .filter_map(|line| {
            let line = line.trim();
            let line = line.strip_prefix("export ").unwrap_or(line);
            if line.starts_with('#') {
                return None;
            }
            let (key, _) = line.split_once('=')?;
            let key = key.trim();
            (!key.is_empty()).then_some((key, line))
        })
        .collect()
}

/// Writes `bytes` to `path` with owner-only permissions on Unix.
fn write_private(path: &Path, bytes: &[u8]) -> io::Result<()> {
    {
        use std::io::Write;
        let mut file = std::fs::OpenOptions::new()
            .create(true)
            .append(true)
            .open(path)?;
        file.write_all(bytes)?;
    }
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        std::fs::set_permissions(path, std::fs::Permissions::from_mode(0o600))?;
    }
    Ok(())
}

/// Generates a random secret appropriate for `key`.
///
/// - `APP_SECRET_KEY`: 64 lowercase hex chars (32 bytes of entropy) —
///   comfortably inside the 32–1024 printable-ASCII validation window
///   and sized for HMAC/token-signing use.
/// - `APP_DB_USER`: `kaladoc_` + 16 hex chars — readable, still unique.
/// - `APP_DB_PASSWORD`: 48 hex chars (24 bytes).
fn generate_secret(key: &str) -> String {
    match key {
        "APP_SECRET_KEY" => hex::encode(random_bytes(32)),
        "APP_DB_USER" => format!("kaladoc_{}", hex::encode(random_bytes(8))),
        "APP_DB_PASSWORD" => hex::encode(random_bytes(24)),
        _ => unreachable!("unknown secret key {key}"),
    }
}

fn random_bytes(n: usize) -> Vec<u8> {
    let mut buf = vec![0u8; n];
    OsRng.fill_bytes(&mut buf);
    buf
}

#[cfg(test)]
mod tests {
    use super::*;

    fn temp_env(tag: &str) -> PathBuf {
        let dir = std::env::temp_dir().join(format!(
            "kaladoc-envfile-{tag}-{}-{}",
            std::process::id(),
            std::time::SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .map(|d| d.as_nanos())
                .unwrap_or(0)
        ));
        std::fs::create_dir_all(&dir).unwrap();
        dir.join(".env")
    }

    #[test]
    fn generates_all_missing_keys() {
        let path = temp_env("all");
        // Ensure env vars are absent for the test (they are in CI; if a
        // dev shell exports them the assertions below adapt).
        let report = ensure_env_file(&path).unwrap();
        assert!(report.modified);
        let text = std::fs::read_to_string(&path).unwrap();
        for key in SECRET_KEYS {
            assert!(text.contains(&format!("{key}=")), "missing {key}");
        }
        // APP_SECRET_KEY must satisfy config validation rules.
        let secret = text
            .lines()
            .find_map(|l| l.strip_prefix("APP_SECRET_KEY="))
            .unwrap();
        assert!(secret.len() >= 32 && secret.len() <= 1024);
        assert!(secret.chars().all(|c| c.is_ascii_graphic()));
    }

    #[test]
    fn preserves_existing_keys_and_appends_missing() {
        let path = temp_env("partial");
        std::fs::write(&path, "APP_SECRET_KEY=existing-value-0123456789abcdef\n").unwrap();
        let report = ensure_env_file(&path).unwrap();
        assert!(report.modified);
        let text = std::fs::read_to_string(&path).unwrap();
        assert!(text.contains("APP_SECRET_KEY=existing-value-0123456789abcdef"));
        assert!(text.contains("APP_DB_USER="));
        assert!(text.contains("APP_DB_PASSWORD="));
        // Existing value must appear exactly once.
        assert_eq!(text.matches("APP_SECRET_KEY=").count(), 1);
    }

    #[test]
    fn second_run_is_a_noop() {
        let path = temp_env("idempotent");
        ensure_env_file(&path).unwrap();
        let first = std::fs::read_to_string(&path).unwrap();
        let report = ensure_env_file(&path).unwrap();
        assert!(!report.modified);
        assert_eq!(std::fs::read_to_string(&path).unwrap(), first);
    }

    #[test]
    fn file_is_owner_only_on_unix() {
        let path = temp_env("perms");
        ensure_env_file(&path).unwrap();
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            let mode = std::fs::metadata(&path).unwrap().permissions().mode() & 0o777;
            assert_eq!(mode, 0o600);
        }
    }
}
