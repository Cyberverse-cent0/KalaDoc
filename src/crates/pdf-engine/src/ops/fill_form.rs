#[cfg(test)]
mod tests {
    use lopdf::{Document, Object, dictionary};

    use super::*;
    use crate::crates::pdf_engine::ops::form_fields::{
        TextFieldSpec, create_text_field, list_form_fields,
    };
    use crate::crates::pdf_engine::ops::test_utils::pdf_with_pages;

    fn limits() -> EngineLimits {
        EngineLimits::default()
    }

    fn text_spec(name: &str, value: Option<&str>) -> TextFieldSpec {
        TextFieldSpec {
            name: name.to_string(),
            page: 1,
            rect: [50.0, 700.0, 250.0, 720.0],
            value: value.map(str::to_string),
            read_only: false,
        }
    }

    fn field_value(pdf: &[u8], name: &str) -> Option<String> {
        list_form_fields(pdf, &limits())
            .unwrap()
            .into_iter()
            .find(|f| f.name == name)
            .and_then(|f| f.value)
    }

    #[test]
    fn fill_sets_v_and_clear_removes_it() {
        let base = pdf_with_pages(&["form page"]);
        let created = create_text_field(&base, &text_spec("name", None), &limits()).unwrap();

        let filled = fill_form(
            &created,
            &[("name".to_string(), "Bob".to_string())],
            &limits(),
        )
        .unwrap();
        assert_eq!(field_value(&filled, "name").as_deref(), Some("Bob"));

        // /NeedAppearances must be set on the AcroForm.
        let doc = Document::load_mem(&filled).unwrap();
        let catalog = doc.catalog().unwrap();
        let (_, af) = doc.dereference(catalog.get(b"AcroForm").unwrap()).unwrap();
        let af = af.as_dict().unwrap();
        assert_eq!(
            af.get(b"NeedAppearances").unwrap().as_bool().unwrap(),
            true
        );

        let cleared = clear_form(&filled, &limits()).unwrap();
        assert_eq!(field_value(&cleared, "name"), None);
        // Structure is kept.
        assert_eq!(list_form_fields(&cleared, &limits()).unwrap().len(), 1);
    }

    #[test]
    fn fill_rejects_unknown_and_non_tx_fields() {
        let base = pdf_with_pages(&["p"]);
        let created = create_text_field(&base, &text_spec("a", None), &limits()).unwrap();
        assert!(matches!(
            fill_form(&created, &[("missing".to_string(), "x".to_string())], &limits()),
            Err(PdfError::InvalidInput(_))
        ));
        // Empty values list is a no-op.
        let out = fill_form(&created, &[], &limits()).unwrap();
        assert_eq!(out, created);
    }

    #[test]
    fn fill_choice_field_validates_options() {
        // Build a PDF with a Ch field offering [(export1)(display1) (export2)].
        let mut doc = Document::with_version("1.5");
        let pages_id = doc.new_object_id();
        let page_id = doc.add_object(dictionary! {
            "Type" => "Page",
            "Parent" => pages_id,
            "MediaBox" => vec![0.into(), 0.into(), 595.into(), 842.into()],
        });
        doc.objects.insert(
            pages_id,
            Object::Dictionary(dictionary! {
                "Type" => "Pages",
                "Kids" => vec![Object::Reference(page_id)],
                "Count" => 1,
                "MediaBox" => vec![0.into(), 0.into(), 595.into(), 842.into()],
            }),
        );
        let catalog_id = doc.add_object(dictionary! {
            "Type" => "Catalog",
            "Pages" => pages_id,
        });
        doc.trailer.set("Root", catalog_id);

        let field_id = doc.add_object(dictionary! {
            "FT" => "Ch",
            "T" => text_string("color"),
            "Opt" => vec![
                Object::Array(vec![text_string("red"), text_string("Red")]),
                text_string("blue"),
            ],
        });
        let acro_id = doc.add_object(dictionary! {
            "Fields" => vec![Object::Reference(field_id)],
        });
        doc.get_dictionary_mut(catalog_id)
            .unwrap()
            .set("AcroForm", acro_id);
        let mut buf = Vec::new();
        doc.save_to(&mut buf).unwrap();

        // Export value "red" (first of the pair) is accepted.
        let filled = fill_form(
            &buf,
            &[("color".to_string(), "red".to_string())],
            &limits(),
        )
        .unwrap();
        assert_eq!(field_value(&filled, "color").as_deref(), Some("red"));

        // Display text and unknown values are rejected.
        for bad in ["Red", "green"] {
            assert!(matches!(
                fill_form(&buf, &[("color".to_string(), bad.to_string())], &limits()),
                Err(PdfError::InvalidInput(_))
            ));
        }
    }

    #[test]
    fn fill_regenerates_existing_appearance() {
        let base = pdf_with_pages(&["p"]);
        let created = create_text_field(&base, &text_spec("n", Some("old")), &limits()).unwrap();

        // Give the merged widget a stale /AP stream, as a real producer would.
        let mut doc = Document::load_mem(&created).unwrap();
        let fields = list_form_fields(&created, &limits()).unwrap();
        let field_name = fields[0].name.clone();
        let _ = field_name;
        // Find the field object id via the AcroForm /Fields array.
        let catalog = doc.catalog().unwrap();
        let (_, af) = doc.dereference(catalog.get(b"AcroForm").unwrap()).unwrap();
        let af = af.as_dict().unwrap();
        let (_, fields_arr) = doc
            .dereference(af.get(b"Fields").unwrap())
            .unwrap();
        let first = fields_arr.as_array().unwrap()[0].as_reference().unwrap();
        let ap_id = doc.add_object(Stream::new(
            dictionary! {
                "Type" => "XObject",
                "Subtype" => "Form",
                "BBox" => vec![0.into(), 0.into(), 200.into(), 20.into()],
            },
            b"q Q\n".to_vec(),
        ));
        doc.get_dictionary_mut(first)
            .unwrap()
            .set("AP", dictionary! { "N" => ap_id });
        let mut with_ap = Vec::new();
        doc.save_to(&mut with_ap).unwrap();

        let filled = fill_form(
            &with_ap,
            &[("n".to_string(), "new-value".to_string())],
            &limits(),
        )
        .unwrap();

        // The AP stream content must now contain the new value.
        let doc = Document::load_mem(&filled).unwrap();
        let (_, af) = doc
            .dereference(doc.catalog().unwrap().get(b"AcroForm").unwrap())
            .unwrap();
        let (_, fields_arr) = doc
            .dereference(af.as_dict().unwrap().get(b"Fields").unwrap())
            .unwrap();
        let fid = fields_arr.as_array().unwrap()[0].as_reference().unwrap();
        let field = doc.get_dictionary(fid).unwrap();
        let (_, ap) = doc.dereference(field.get(b"AP").unwrap()).unwrap();
        let ap = ap.as_dict().unwrap();
        let (_, n) = doc.dereference(ap.get(b"N").unwrap()).unwrap();
        let stream = n.as_stream().unwrap();
        let content = String::from_utf8_lossy(&stream.content);
        assert!(content.contains("(new-value) Tj"), "content: {content}");
        assert!(content.contains("/Helv"));
    }

    #[test]
    fn clear_form_without_acroform_is_noop() {
        let base = pdf_with_pages(&["plain"]);
        let out = clear_form(&base, &limits()).unwrap();
        assert_eq!(out, base);
    }
}
