//! Fill and clear AcroForm field values.
//!
//! [`fill_form`] sets `/V` on fields whose **full dotted name** matches
//! an entry in `values` exactly (case-sensitive). Only text (`Tx`)
//! and choice (`Ch`) fields are fillable:
//!
//! - `Tx`: any string is accepted.
//! - `Ch`: the value must be one of the field's `/Opt` **export
//!   values** (the first element of `[export, display]` pairs); a
//!   value outside `/Opt` — or a choice field with no usable `/Opt` —
//!   is rejected with [`PdfError::InvalidInput`] *before* any
//!   mutation happens, so a failed call never produces a half-filled
//!   document.
//!
//! All names are resolved and validated first; only then are `/V`
//! entries written, so errors are atomic with respect to the input.
//!
//! # Appearance regeneration (honest scope)
//!
//! After `/V` is updated, `/AcroForm /NeedAppearances` is set to
//! `true` so conforming viewers regenerate appearances themselves.
//! Additionally, for every widget annotation that already carries an
//! `/AP` entry, a **simple appearance stream is regenerated**: a Form
//! XObject whose `/BBox` matches the widget `/Rect`, drawing the new
//! value in black 10 pt Helvetica (`/Helv` from `/AcroForm /DR`,
//! created on demand). Widgets *without* `/AP` are left alone —
//! viewers generate their appearance via `/NeedAppearances`.
//!
//! Known limitations of the regenerated appearance:
//!
//! - Text is drawn with the base-14 Helvetica font using PDF
//!   literal-string bytes; **non-ASCII text is written as UTF-8**,
//!   which simple fonts cannot encode correctly (it may render as
//!   mojibake until a viewer regenerates the appearance).
//! - Multi-line values, complex scripts and right-to-left text are
//!   not handled — the value is drawn on a single baseline.
//! - `/AP /N` given as a *dictionary of appearance states* is replaced
//!   wholesale by the single regenerated stream (fine for `Tx`/`Ch`,
//!   which do not use `/AS` states).
//!
//! [`clear_form`] removes `/V` from every field in the tree (structure,
//! `/Opt`, flags and widget annotations are kept) and also sets
//! `/NeedAppearances true` so stale appearances are regenerated by the
//! viewer. Appearance streams themselves are *not* rewritten — they
//! may still show the old value until a viewer regenerates them.

use lopdf::{Document, Object, ObjectId, Stream, dictionary, text_string};

use crate::crates::core::engine::EngineLimits;

use crate::crates::pdf_engine::error::{PdfError, PdfResult};

use super::form_fields::{
    acroform_dict_id, collect_fields, ensure_helv_font, escape_pdf_literal,
    normalize_acroform, set_need_appearances, FieldEntry,
};
use super::load::{load_pdf, lopdf_err, reject_encrypted, save_pdf};

/// Fill form fields in `input` with `values` (`(full name, value)`
/// pairs) and return the modified PDF.
///
/// Matching is exact and case-sensitive on the full dotted field
/// name. When several fields share a name, the first in document
/// order is filled. Duplicate `(name, value)` pairs are applied in
/// order (last write wins).
pub fn fill_form(input: &[u8], values: &[(String, String)], limits: &EngineLimits) -> PdfResult<Vec<u8>> {
    let mut doc = load_pdf(input, limits)?;
    reject_encrypted(&doc)?;

    if values.is_empty() {
        return Ok(input.to_vec());
    }
    let acro_id = match acroform_dict_id(&doc)? {
        Some(id) => id,
        None => {
            return Err(PdfError::InvalidInput(
                "document has no AcroForm fields".to_string(),
            ));
        }
    };
    // Promote inline field/widget dictionaries so every field has an
    // object id to mutate.
    normalize_acroform(&mut doc)?;
    let entries = collect_fields(&doc);

    // Pass 1 — resolve and validate everything before mutating.
    let mut ops: Vec<(&FieldEntry, &str)> = Vec::with_capacity(values.len());
    let mut missing: Vec<&str> = Vec::new();
    for (name, value) in values {
        let Some(entry) = entries
            .iter()
            .find(|e| e.name == *name && (e.type_name == "Tx" || e.type_name == "Ch"))
        else {
            missing.push(name);
            continue;
        };
        if entry.type_name == "Ch"
            && (entry.options.is_empty() || !entry.options.iter().any(|o| o == value))
        {
            return Err(PdfError::InvalidInput(format!(
                "value {value:?} is not an allowed option for choice field {name:?}"
            )));
        }
        if entry.id.is_none() {
            return Err(PdfError::InvalidInput(format!(
                "field {name:?} is not an editable indirect object"
            )));
        }
        ops.push((entry, value.as_str()));
    }
    if !missing.is_empty() {
        let list = missing
            .iter()
            .map(|n| format!("{n:?}"))
            .collect::<Vec<_>>()
            .join(", ");
        return Err(PdfError::InvalidInput(format!(
            "no fillable text/choice field named {list}"
        )));
    }

    // Pass 2 — write /V and regenerate widget appearances.
    let mut helv: Option<ObjectId> = None;
    for (entry, value) in ops {
        let field_id = entry.id.expect("checked in pass 1");
        doc.get_object_mut(field_id)
            .map_err(lopdf_err)?
            .as_dict_mut()
            .map_err(lopdf_err)?
            .set("V", text_string(value));

        for widget in &entry.widgets {
            if let (Some(widget_id), Some(rect)) = (widget.id, widget.rect) {
                regenerate_appearance(&mut doc, acro_id, &mut helv, widget_id, rect, value)?;
            }
        }
    }

    set_need_appearances(&mut doc, acro_id);
    save_pdf(&mut doc)
}

/// Clear `/V` on every form field in `input` and return the modified
/// PDF. Field structure, `/Opt` options, flags and widget annotations
/// are preserved. Documents without an `/AcroForm` are returned
/// unchanged.
pub fn clear_form(input: &[u8], limits: &EngineLimits) -> PdfResult<Vec<u8>> {
    let mut doc = load_pdf(input, limits)?;
    reject_encrypted(&doc)?;

    let Some(acro_id) = acroform_dict_id(&doc)? else {
        return Ok(input.to_vec());
    };
    normalize_acroform(&mut doc)?;
    let entries = collect_fields(&doc);

    for entry in &entries {
        let Some(field_id) = entry.id else {
            continue;
        };
        doc.get_object_mut(field_id)
            .map_err(lopdf_err)?
            .as_dict_mut()
            .map_err(lopdf_err)?
            .remove(b"V");
    }

    set_need_appearances(&mut doc, acro_id);
    save_pdf(&mut doc)
}

/// Replace a widget's `/AP` with a freshly generated single-state
/// appearance stream showing `value`, but only when the widget
/// already has an `/AP` entry (widgets without one are left for the
/// viewer to generate via `/NeedAppearances`).
fn regenerate_appearance(
    doc: &mut Document,
    acro_id: ObjectId,
    helv: &mut Option<ObjectId>,
    widget_id: ObjectId,
    rect: [f64; 4],
    value: &str,
) -> PdfResult<()> {
    let has_ap = match doc.get_dictionary(widget_id) {
        Ok(dict) => dict.has(b"AP"),
        Err(_) => return Ok(()),
    };
    if !has_ap {
        return Ok(());
    }
    let width = rect[2] - rect[0];
    let height = rect[3] - rect[1];
    if !(width.is_finite() && height.is_finite() && width > 0.0 && height > 0.0) {
        return Ok(());
    }

    // Lazily ensure the /Helv resource only when an appearance is
    // actually regenerated.
    let font_id = match helv {
        Some(id) => *id,
        None => {
            let id = ensure_helv_font(doc, acro_id)?;
            *helv = Some(id);
            id
        }
    };

    let mut content = String::with_capacity(value.len() + 64);
    content.push_str("q\nBT /Helv 10 Tf 2 ");
    content.push_str(&format!("{}", (height - 12.0).max(1.0)));
    content.push_str(" Td (");
    content.push_str(&String::from_utf8_lossy(&escape_pdf_literal(value)));
    content.push_str(") Tj ET\nQ\n");

    let stream = Stream::new(
        dictionary! {
            "Type" => "XObject",
            "Subtype" => "Form",
            "FormType" => 1,
            "BBox" => vec![
                Object::from(0.0f64),
                Object::from(0.0f64),
                Object::from(width),
                Object::from(height),
            ],
            "Resources" => dictionary! {
                "Font" => dictionary! {
                    "Helv" => font_id,
                },
            },
        },
        content.into_bytes(),
    );
    let stream_id = doc.add_object(Object::Stream(stream));

    let dict = doc
        .get_object_mut(widget_id)
        .map_err(lopdf_err)?
        .as_dict_mut()
        .map_err(lopdf_err)?;
    dict.set("AP", dictionary! { "N" => stream_id });
    dict.remove(b"AS");
    Ok(())
}

